#!/usr/bin/env bash
# Regenerate the *_BIN_SHA256_<os>_<arch> table of tools.lock (RQ11).
# For every tool x platform it downloads the REAL release asset, verifies it against the
# asset sha256 already in tools.lock (<TOOL>_SHA256_<os>_<arch>), extracts the executable
# and prints the sha256 of that executable — the value `sbomgate check-tools` compares.
#
#   scripts/lock-bin-hashes.sh [--lock FILE] [--cache DIR] [--write]
#     --lock   tools.lock to read (default: <repo>/tools.lock)
#     --cache  keep downloads here and reuse them on the next run (default: a temp dir, deleted)
#     --write  replace the BIN table at the end of --lock in place (default: print to stdout)
# Exit: 0 ok · 1 download / checksum / extract failure (nothing is written on failure).
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
LOCK="$HERE/tools.lock"; CACHE=""; WRITE=0
while [ $# -gt 0 ]; do
  case "$1" in
    --lock) LOCK="$2"; shift 2;; --cache) CACHE="$2"; shift 2;; --write) WRITE=1; shift;;
    -h|--help) sed -n '2,11p' "$0" | sed 's/^# \{0,1\}//'; exit 0;;
    *) echo "unknown argument: $1" >&2; exit 64;;
  esac
done
[ -f "$LOCK" ] || { echo "lock file not found: $LOCK" >&2; exit 1; }
lockval() { sed -n "s/^$1=//p" "$LOCK" | head -1; }
sha256_of() { if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
if [ -z "$CACHE" ]; then CACHE="$TMP/cache"; fi
mkdir -p "$CACHE"

SYFT_VERSION="$(lockval SYFT_VERSION)"; GRYPE_VERSION="$(lockval GRYPE_VERSION)"; TRIVY_VERSION="$(lockval TRIVY_VERSION)"
YQ_VERSION="$(lockval YQ_VERSION)"; JQ_VERSION="$(lockval JQ_VERSION)"; COSIGN_VERSION="$(lockval COSIGN_VERSION)"
COSIGN_LINUX_VARIANT="$(lockval COSIGN_LINUX_VARIANT)"
for v in SYFT_VERSION GRYPE_VERSION TRIVY_VERSION YQ_VERSION JQ_VERSION COSIGN_VERSION; do
  eval "[ -n \"\$$v\" ]" || { echo "$v missing in $LOCK" >&2; exit 1; }
done

# asset URL + the member to extract ("" = the asset IS the executable)
asset() {  # $1 tool  $2 os  $3 arch   -> prints "url<TAB>member"
  local t="$1" os="$2" arch="$3" ext=tar.gz exe="" tos tarch jos cv
  [ "$os" = windows ] && { ext=zip; exe=.exe; }
  case "$t" in
    syft)  printf 'https://github.com/anchore/syft/releases/download/v%s/syft_%s_%s_%s.%s\tsyft%s\n' "$SYFT_VERSION" "$SYFT_VERSION" "$os" "$arch" "$ext" "$exe";;
    grype) printf 'https://github.com/anchore/grype/releases/download/v%s/grype_%s_%s_%s.%s\tgrype%s\n' "$GRYPE_VERSION" "$GRYPE_VERSION" "$os" "$arch" "$ext" "$exe";;
    trivy)
      case "$os" in linux) tos=Linux;; darwin) tos=macOS;; windows) tos=windows;; esac
      case "$arch" in amd64) tarch=64bit;; arm64) tarch=ARM64;; esac
      printf 'https://github.com/aquasecurity/trivy/releases/download/v%s/trivy_%s_%s-%s.%s\ttrivy%s\n' "$TRIVY_VERSION" "$TRIVY_VERSION" "$tos" "$tarch" "$ext" "$exe";;
    yq)    printf 'https://github.com/mikefarah/yq/releases/download/v%s/yq_%s_%s%s\t\n' "$YQ_VERSION" "$os" "$arch" "$exe";;
    jq)    jos="$os"; [ "$os" = darwin ] && jos=macos
           printf 'https://github.com/jqlang/jq/releases/download/jq-%s/jq-%s-%s%s\t\n' "$JQ_VERSION" "$jos" "$arch" "$exe";;
    cosign) cv="$os"; [ "$os" = linux ] && [ -n "$COSIGN_LINUX_VARIANT" ] && cv="linux-$COSIGN_LINUX_VARIANT"
           printf 'https://github.com/sigstore/cosign/releases/download/v%s/cosign-%s-%s%s\t\n' "$COSIGN_VERSION" "$cv" "$arch" "$exe";;
  esac
}

OUTF="$TMP/bin-table"
{
  echo "# Extracted-executable sha256 (generated by scripts/lock-bin-hashes.sh on $(date -u +%Y-%m-%d); do not edit by hand)"
} > "$OUTF"
for t in syft grype trivy yq jq cosign; do
  T="$(printf '%s' "$t" | tr '[:lower:]' '[:upper:]')"
  for plat in linux_amd64 linux_arm64 darwin_amd64 darwin_arm64 windows_amd64; do
    os="${plat%_*}"; arch="${plat#*_}"
    line="$(asset "$t" "$os" "$arch")"; url="${line%%	*}"; member="${line#*	}"
    want="$(lockval "${T}_SHA256_${plat}")"
    [ -n "$want" ] || { echo "${T}_SHA256_${plat} missing in $LOCK" >&2; exit 1; }
    f="$CACHE/$(basename "$url")"
    if [ ! -f "$f" ] || [ "$(sha256_of "$f")" != "$want" ]; then
      echo "download $url" >&2
      curl -fsSL --retry 3 -o "$f.part" "$url" || { echo "download failed: $url" >&2; exit 1; }
      mv "$f.part" "$f"
    fi
    got="$(sha256_of "$f")"
    [ "$got" = "$want" ] || { echo "asset sha256 mismatch for $url: got $got want $want" >&2; exit 1; }
    if [ -z "$member" ]; then
      bin="$f"
    else
      x="$TMP/x/$t-$plat"; rm -rf "$x"; mkdir -p "$x"
      if ! tar -xf "$f" -C "$x" "$member" 2>/dev/null; then
        (cd "$x" && unzip -o -q "$f" "$member") || { echo "cannot extract $member from $f" >&2; exit 1; }
      fi
      bin="$x/$member"
    fi
    [ -s "$bin" ] || { echo "empty executable for $t $plat" >&2; exit 1; }
    printf '%s_BIN_SHA256_%s=%s\n' "$T" "$plat" "$(sha256_of "$bin")" >> "$OUTF"
    echo "ok $t $plat" >&2
  done
done

if [ "$WRITE" = 1 ]; then
  # drop any previous generated table (its header comment + every *_BIN_SHA256_* line), append the new one
  grep -v -e '_BIN_SHA256_' -e '^# Extracted-executable sha256 (generated' "$LOCK" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' > "$TMP/lock.new"
  { cat "$TMP/lock.new"; echo; cat "$OUTF"; } > "$TMP/lock.final"
  cp "$TMP/lock.final" "$LOCK"
  echo "wrote BIN table to $LOCK" >&2
else
  cat "$OUTF"
fi
